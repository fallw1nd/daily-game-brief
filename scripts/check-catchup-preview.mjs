// Execute the self-contained file without a dev server; not a substitute for visual QA.
import { JSDOM, VirtualConsole } from 'jsdom';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const errors = [];
const vc = new VirtualConsole();
vc.on('jsdomError', error => errors.push(error.message));
vc.on('error', error => errors.push(String(error)));
const dom = new JSDOM(await fs.readFile('preview-artifacts/offline-catchup-preview.html', 'utf8'), { runScripts: 'dangerously', url: 'file:///preview.html', pretendToBeVisual: true, virtualConsole: vc });
const wait = () => new Promise(resolve => setTimeout(resolve, 100));
await wait();
const d = dom.window.document;
assert.equal(d.querySelectorAll('.cu-story').length, 12);
assert.match(d.querySelector('.cu-timeline').textContent, /译名：助手暂译（非官方）/);
assert.match(d.querySelector('.cu-range').textContent, /2026-10-13 — 2026-10-19/);
d.querySelector('.cu-presets button:nth-child(2)').click();
await wait();
assert.match(d.querySelector('.cu-range').textContent, /2026-09-20 — 2026-10-19/);
const select = d.querySelector('select');
select.selectedIndex = 1;
select.dispatchEvent(new dom.window.Event('change', { bubbles: true }));
await wait();
assert.match(d.querySelector('.cu-results-heading').textContent, /主题档案/);
for (const a of d.querySelectorAll('.cu-story a')) assert.ok(a.href.startsWith('https://fallw1nd.github.io/daily-game-brief/?view=reading&edition='));
d.querySelector('.r-controls button').click();
await wait();
assert.equal(d.documentElement.lang, 'en');
assert.match(d.querySelector('.cu-intro').textContent, /Pick up the thread/);
assert.equal(d.querySelectorAll('script[src],link[rel=stylesheet],img').length, 0);
assert.deepEqual(errors, []);
console.log('Portable HTML execution passed: initial load, 30-day filter, topic dossier, English, source-edition URLs, and zero external assets or runtime errors.');
dom.window.close();
